-- Census ACS 1-year county estimates — fresh calendar-year snapshots.
-- Available for ~861 counties (pop >= 65,000). Not a rolling window,
-- so period_end_date corresponds to a specific calendar year.
select
    fips,
    period_end_date,
    median_household_income,
    median_gross_rent,
    median_home_value,
    owner_occupied_units,
    renter_occupied_units,
    vacant_for_rent_units,
    rental_vacancy_rate,
    total_population,
    age_20_34,
    foreign_born_population,
    units_in_5_to_9_bldgs,
    units_in_10_to_19_bldgs,
    units_in_20_to_49_bldgs,
    units_in_50_plus_bldgs,
    hu_built_2020_plus,
    hu_built_2010_to_2019,
    hu_built_2000_to_2009,
    hu_built_1990_to_1999,
    hu_built_1980_to_1989,
    hu_built_1970_to_1979,
    hu_built_1960_to_1969,
    hu_built_1950_to_1959,
    hu_built_1940_to_1949,
    hu_built_pre_1940,
    county_state_name,
    as_of_date
from {{ source('curated', 'census_acs_1yr') }}
